  const owner='a'.repeat(64),id={owner},metadata={source_id:'b'.repeat(64)+':https://example.com/a',kind:'link'};
  const receipt={id:'collection:'+'1'.repeat(24),owner,actor:owner,metadata,next:0,size:0,sha256:createHash('sha256').update('').digest('hex'),state:'uploading'};
