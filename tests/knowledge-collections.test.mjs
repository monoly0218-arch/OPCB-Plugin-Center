test('signed person/Agent deposit originals into the existing knowledge gateway with type filtering, readback and live ACLs',{timeout:45000},async t=>{
  const community='c'.repeat(64),adminKey=generateSecretKey(),personKey=generateSecretKey(),agentKey=generateSecretKey(),otherKey=generateSecretKey();
  const admin=getPublicKey(adminKey),person=getPublicKey(personKey),actor=getPublicKey(agentKey),other=getPublicKey(otherKey);
  const child=spawn(pythonRuntime(),['tests/knowledge_gateway_fixture.py',community,admin,'services/knowledge/dist/identity-auth.mjs',process.execPath,'--collection'],{stdio:['pipe','pipe','pipe']});
  let errors='';child.stderr.on('data',value=>errors+=value);t.after(()=>{if(child.exitCode===null)child.kill()});
  const lines=createInterface({input:child.stdout});
  const [line]=await Promise.race([once(lines,'line'),once(child,'exit').then(()=>{throw Error(errors)})]);
  const base=`http://127.0.0.1:${JSON.parse(line).port}`;
  const host={request:async options=>{const response=await fetch(`${base}/${new URL(options.url).pathname.split('/').at(-1)}`,{method:'POST',headers:{'Content-Type':'application/json'},body:options.body});return{status:response.status,body:await response.text()}}};
  const sign=key=>content=>finalizeEvent({kind:45010,created_at:Math.floor(Date.now()/1000),tags:[['h','private-fixture']],content},key);
  const id=identity(person,community),manager=createIdentityClient(host,{role:'manage',storage:memory()}),adminId=identity(admin,community);
  await manager.bind(adminId,sign(adminKey));
  const reader=createIdentityClient(host,{storage:memory()});await reader.bind(id,sign(personKey));
  await assert.rejects(reader.collect(id,{op:'list'}),{status:403});
  let snapshot=await manager.policy(adminId,{op:'snapshot'});
  const change=async(action,payload)=>{await manager.policy(adminId,{op:'change',expected_revision:snapshot.revision,action,payload});snapshot=await manager.policy(adminId,{op:'snapshot'})};
  await change('grant',{owner:person,library:'collected-artifacts',allow:true});
  const agent=createIdentityClient(host,{storage:memory(),role:'collect',actor,actorScoped:true});
  await agent.bind(id,content=>{const auth=Buffer.from(schnorr.sign(Buffer.from(sha(`nostr:agent-auth:${actor}:`),'hex'),personKey)).toString('hex');return finalizeEvent({kind:30023,created_at:Math.floor(Date.now()/1000),tags:[['d','fixture'],['auth',person,'',auth]],content},agentKey)});
  const bytes=new Uint8Array(300000).fill(65);bytes.set([137,80,78,71,13,10,26,10]);
  const sourceId='f'.repeat(64)+':https://example.com/main.png';
  const metadata={source_id:sourceId,title:'品牌主图',kind:'image',source_url:'https://example.com/main.png',channel_id:'private-fixture',message_id:'f'.repeat(64),tags:['品牌'],group_id:'g-main',group_title:'品牌主图',version:3};
  await assert.rejects(reader.collect(id,{op:'begin',metadata,upload:{size:0,sha256:'0'.repeat(64),mime:'text/uri-list'}}),{status:403});
  const controller=new AbortController();
  const saved=await commitDeposit(agent,id,metadata,{bytes,mime:'image/png'},controller.signal);
  assert.equal(saved.operator,actor);assert.equal(saved.storage,'original');
  const marked=curate(emptyCuration(),{type:'archive',ids:[sourceId],receipt:saved,owner:person,actor,actorKind:'agent'});assert.equal(marked.assets[sourceId].id,saved.id);
  assert.equal((await reader.read(id,{op:'catalog'})).sources.find(s=>s.source_id==='collection').documents,1);
  assert.equal((await reader.read(id,{op:'list',source:'collection',kind:'image'})).results.length,1);
  assert.equal((await reader.read(id,{op:'list',source:'collection',kind:'document'})).results.length,0);
  assert.equal((await reader.read(id,{op:'search',source:'collection',query:'品牌'})).results[0].id,saved.id);
  const browsing=await reader.read(id,{op:'browse',space:'all',kind:'image'});
  assert.equal(browsing.results[0].id,saved.id);
  assert.equal(browsing.results[0].organization.shared,false);
  const doc=await reader.read(id,{op:'get',source:'collection',id:saved.id});
  assert.equal(doc.note.collection.metadata.version,3);
  const restored=await readCollectedFile(reader,id,doc.note.collection,controller.signal);
  assert.equal(createHash('sha256').update(restored).digest('hex'),saved.sha256);
  assert.equal((await commitDeposit(agent,id,metadata,{bytes,mime:'image/png'},controller.signal)).id,saved.id);
  assert.equal((await reader.collect(id,{op:'list'})).results.length,1);
  const wrong=createIdentityClient(host,{storage:memory(),actor});await wrong.bind(id,sign(personKey)).then(()=>assert.fail('must not bind person bytes as an agent')).catch(error=>assert.match(error.message,/不匹配/));
  const otherReader=createIdentityClient(host,{storage:memory()}),otherId=identity(other,community);await otherReader.bind(otherId,sign(otherKey));
  await change('grant',{owner:other,library:'collected-artifacts',allow:true});
  assert.deepEqual((await otherReader.collect(otherId,{op:'list'})).results,[]);
  await assert.rejects(otherReader.collect(otherId,{op:'get',id:saved.id}),{status:403});
  await assert.rejects(agent.policy(id,{op:'snapshot'}),{status:403});
  await change('disable',{owner:person,disabled:true});
  await assert.rejects(agent.collect(id,{op:'get',id:saved.id}),{status:403});
  await assert.rejects(reader.read(id,{op:'get',source:'collection',id:saved.id},{cacheOnly:true}),error=>error.denied);
  child.stdin.end('\n');const [code]=await once(child,'exit');assert.equal(code,0,errors);
});
