import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {createInterface} from 'node:readline';
import {randomBytes,webcrypto} from 'node:crypto';
import {generateSecretKey,getPublicKey,finalizeEvent} from 'nostr-tools/pure';
import {schnorr} from '@noble/curves/secp256k1.js';
import {sha,fingerprint,AUDIENCE} from '../services/knowledge/identity_auth.mjs';
import {pythonRuntime} from '../scripts/python_runtime.mjs';
import {createIdentityClient,identity} from '../src/knowledge/identity-client.mjs';
import {markdownBlocks,safeURL} from '../src/knowledge/reader.mjs';

test('real signatures, HTTP gateway, owner inheritance, immediate revocation and encrypted cache', {timeout:40000},async t=>{
  const community='c'.repeat(64),adminKey=generateSecretKey(),personKey=generateSecretKey();
  const admin=getPublicKey(adminKey),person=getPublicKey(personKey);
  const child=spawn(pythonRuntime(),['tests/knowledge_gateway_fixture.py',community,admin,'services/knowledge/dist/identity-auth.mjs',process.execPath],{stdio:['pipe','pipe','pipe']});
  let errors='';child.stderr.on('data',v=>errors+=v);
  t.after(()=>{if(child.exitCode===null)child.kill();});
  const lines=createInterface({input:child.stdout});
  const [line]=await Promise.race([once(lines,'line'),once(child,'exit').then(()=>{throw Error(errors);})]);
  const base=`http://127.0.0.1:${JSON.parse(line).port}`;
  const post=async(action,value)=>{
    const r=await fetch(`${base}/${action}`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(value)});
    return {status:r.status,body:await r.text()};
  };
  const host={request:async r=>post(new URL(r.url).pathname.split('/').at(-1),JSON.parse(r.body))};
  const storage=()=>{const data=new Map();return {data,get:async k=>data.get(k),put:async(k,v)=>data.set(k,v),remove:async k=>data.delete(k)};};
  const store=storage(),reader=createIdentityClient(host,{storage:store}),manager=createIdentityClient(host,{role:'manage',storage:storage()});
  const adminId=identity(admin,community),personId=identity(person,community);
  const sign=key=>content=>finalizeEvent({kind:45010,created_at:Math.floor(Date.now()/1000),tags:[['h','private-fixture']],content},key);
  const signAgent=(ownerKey,agentKey)=>content=>{
    const actor=getPublicKey(agentKey),owner=getPublicKey(ownerKey);
    const auth=Buffer.from(schnorr.sign(Buffer.from(sha(`nostr:agent-auth:${actor}:`),'hex'),ownerKey)).toString('hex');
    return finalizeEvent({kind:30023,created_at:Math.floor(Date.now()/1000),tags:[['d','fixture'],['auth',owner,'',auth]],content},agentKey);
  };
  await manager.bind(adminId,sign(adminKey));
  await reader.bind(personId,sign(personKey));
  await assert.rejects(reader.collect(personId,{op:'list'}),{status:404});
  assert.deepEqual((await reader.read(personId,{op:'catalog'})).sources,[]);
  await assert.rejects(reader.read(personId,{op:'get',source:'recordings',id:'100'}),{status:403});
  let snapshot=await manager.policy(adminId,{op:'snapshot'});
  const grant=async(action,payload)=>{
    const changed=await manager.policy(adminId,{op:'change',expected_revision:snapshot.revision,action,payload});
    snapshot=await manager.policy(adminId,{op:'snapshot'});assert.equal(snapshot.revision,changed.revision);
  };
  await grant('grant',{owner:person,library:'work-records',allow:true});
  await grant('library',{id:'work-records',name:'工作计划与会议',parent:'company'});
  const catalog=await reader.read(personId,{op:'catalog'});
  assert.deepEqual(catalog.sources.map(s=>s.source_id),['recordings']);
  assert.equal(catalog.sources[0].display_name,'工作计划与会议');
  assert.equal((await reader.read(personId,{op:'list',source:'recordings',limit:20,offset:0})).results[0].id,'100');
  assert.equal((await reader.read(personId,{op:'search',source:'recordings',query:'Fixture'})).results[0].id,'100');
  assert.match((await reader.read(personId,{op:'get',source:'recordings',id:'100'})).note.content,/Private fixture/);
  assert.equal((await reader.read(personId,{op:'get',source:'recordings',id:'100'},{cacheOnly:true})).cache.cached,true);
  const record=[...store.data.values()][0];
  assert.equal(record.keys.privateKey.extractable,false);assert.equal(record.cacheKey.extractable,false);
  assert.equal(Buffer.from(record.cache).includes(Buffer.from('Private fixture')),false);
  assert.equal((await createIdentityClient(host,{storage:store}).status(personId)).connected,true);
  const newAgent=createIdentityClient(host,{storage:storage()});
  await newAgent.bind(personId,signAgent(personKey,generateSecretKey()));
  assert.match((await newAgent.read(personId,{op:'get',source:'recordings',id:'100'})).note.content,/Private fixture/);
  assert.equal(snapshot.grants.filter(g=>g.owner===person).length,1);
  await assert.rejects(newAgent.policy(personId,{op:'snapshot'}),{status:403});
  const adminRead=createIdentityClient(host,{storage:storage()});await adminRead.bind(adminId,sign(adminKey));
  await assert.rejects(adminRead.policy(adminId,{op:'snapshot'}),{status:403});
  await assert.rejects(createIdentityClient(host,{role:'manage',storage:storage()}).bind(adminId,signAgent(adminKey,generateSecretKey())),{status:403});
  await assert.rejects(reader.read(personId,{op:'get',source:'research',id:'research:'+'a'.repeat(24)}),{status:403});
  const cachedRevision=snapshot.revision;
  await grant('disable',{owner:person,disabled:true});
  await assert.rejects(reader.read(personId,{op:'get',source:'recordings',id:'100'},{cacheOnly:true}),e=>e.denied);
  assert.equal((await reader.status(personId)).cachedDocuments,0);
  assert.deepEqual((await newAgent.read(personId,{op:'catalog'})).sources,[]);
  assert.deepEqual((await reader.read(personId,{op:'catalog'},{cacheOnly:true})).sources,[]);
  await assert.rejects(manager.policy(adminId,{op:'change',expected_revision:cachedRevision,action:'disable',payload:{owner:person,disabled:false}}),{status:409});
  assert.equal((await post('read',{owner:admin,body:'{}',proof:{}})).status,400);
  const body=JSON.stringify({request:{op:'catalog'}}),nonce=randomBytes(32).toString('hex'),timestamp=Math.floor(Date.now()/1000);
  const deviceRecord=record;
  const signature=Buffer.from(await webcrypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},deviceRecord.keys.privateKey,Buffer.from(JSON.stringify(['opcb.knowledge.request.v1',`${AUDIENCE}/read`,body,nonce,timestamp])))).toString('base64url');
  const proof={device:fingerprint(deviceRecord.deviceKey),nonce,timestamp,signature};
  assert.equal((await post('read',{body,proof})).status,200);
  assert.equal((await post('read',{body,proof})).status,403);
  assert.equal((await post('read',{body:'{}',proof:{...proof,nonce:randomBytes(32).toString('hex')}})).status,403);
  await grant('disable',{owner:person,disabled:false});
  assert.match((await reader.read(personId,{op:'get',source:'recordings',id:'100'})).note.content,/Private fixture/);
  const close=once(child,'exit');child.stdin.end('\n');const [code]=await close;assert.equal(code,0,errors);lines.close();
});

test('reader parses headings, plans and tables while keeping URLs safe',()=>{
  const blocks=markdownBlocks('# 计划\n\n| 工作 | 负责人 |\n| --- | --- |\n| 包装 | A |\n\n- 清单\n\n```\n<script>test</script>\n```');
  assert.deepEqual(blocks.map(b=>b.kind),['heading','table','item','code']);
  assert.equal(blocks[1].rows[0][0],'包装');
  for(const u of ['javascript:alert(1)','data:text/html,test','https://user:pass@example.com'])assert.equal(safeURL(u),null);
  assert.equal(safeURL('https://example.com/note'),'https://example.com/note');
});
